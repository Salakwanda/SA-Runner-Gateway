const Database = require("better-sqlite3");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const configuredDatabasePath = process.env.DATABASE_PATH;
const databasePath = configuredDatabasePath
  ? path.resolve(configuredDatabasePath)
  : path.join(__dirname, "errands.db");

fs.mkdirSync(path.dirname(databasePath), { recursive: true });
const db = new Database(databasePath);

db.pragma("journal_mode = WAL");

db.exec(`
    
  CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('CLIENT', 'RUNNER', 'ADMIN')),
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS runner_profiles (
    user_id TEXT PRIMARY KEY,
    city TEXT NOT NULL,
    id_number TEXT NOT NULL,
    id_doc_url TEXT,
    proof_res_url TEXT,
    affidavit_url TEXT,
    is_verified INTEGER DEFAULT 0 CHECK(is_verified IN (0, 1)),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS errands (
    id TEXT PRIMARY KEY,
    client_id TEXT NOT NULL,
    runner_id TEXT,
    pickup_city TEXT NOT NULL,
    dropoff_city TEXT NOT NULL,
    delivery_method TEXT NOT NULL,
    item_description TEXT NOT NULL,
    reward_amount REAL NOT NULL,
    status TEXT DEFAULT 'PENDING' CHECK(status IN ('PENDING', 'ACCEPTED', 'IN_TRANSIT', 'COMPLETED', 'CANCELLED')),
    paxi_waybill_no TEXT,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES users(id),
    FOREIGN KEY (runner_id) REFERENCES users(id)
  );

  CREATE TABLE IF NOT EXISTS messages (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    errand_id TEXT NOT NULL,
    sender_id TEXT NOT NULL,
    message_text TEXT NOT NULL,
    sent_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (errand_id) REFERENCES errands(id) ON DELETE CASCADE,
    FOREIGN KEY (sender_id) REFERENCES users(id)
  );
`);

try {
  db.exec("ALTER TABLE users ADD COLUMN password_hash TEXT");
} catch (error) {
  if (!error.message.includes("duplicate column name")) throw error;
}

const generateUserId = (role) =>
  `USR-${role}-${Math.floor(1000 + Math.random() * 9000)}`;
const generateTrackingId = () =>
  `RUN-ZA-${Math.floor(100000 + Math.random() * 900000)}`;

const hashPassword = (
  password,
  salt = crypto.randomBytes(16).toString("hex"),
) => {
  const hash = crypto.scryptSync(password, salt, 64).toString("hex");
  return `${salt}:${hash}`;
};

const adminPasswordHash = hashPassword("Admin@123");

const getUserIdByEmail = db.prepare(`SELECT id FROM users WHERE email = ?`);
function ensureUser(id, full_name, email, phone, role, passwordHash = null) {
  const existing = getUserIdByEmail.get(email);
  if (existing) {
    if (passwordHash) {
      db.prepare("UPDATE users SET password_hash = ? WHERE email = ?").run(
        passwordHash,
        email,
      );
    }
    return existing.id;
  }

  db.prepare(
    "INSERT INTO users (id, full_name, email, phone, role, password_hash) VALUES (?, ?, ?, ?, ?, ?)",
  ).run(id, full_name, email, phone, role, passwordHash);
  return id;
}

const errand1Id = generateTrackingId();

const insertUser = db.prepare(`
  INSERT OR IGNORE INTO users (id, full_name, email, phone, role, password_hash)
  VALUES (?, ?, ?, ?, ?, ?)
`);

const insertRunnerProfile = db.prepare(`
  INSERT OR IGNORE INTO runner_profiles (user_id, city, id_number, is_verified)
  VALUES (?, ?, ?, ?)
`);

const insertErrand = db.prepare(`
  INSERT OR IGNORE INTO errands (id, client_id, runner_id, pickup_city, dropoff_city, delivery_method, item_description, reward_amount, status)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
`);

const insertMessage = db.prepare(`
  INSERT INTO messages (errand_id, sender_id, message_text)
  VALUES (?, ?, ?)
`);

db.transaction(() => {
  // Insert Users (create or reuse by email)
  const client1Id = ensureUser(
    generateUserId("CLIENT"),
    "Sipho Dlamini",
    "sipho@example.com",
    "0821234567",
    "CLIENT",
  );
  const runner1Id = ensureUser(
    generateUserId("RUNNER"),
    "Thabo Mokoena",
    "thabo@example.com",
    "0839876543",
    "RUNNER",
  );
  const admin1Id = ensureUser(
    generateUserId("ADMIN"),
    "System Admin",
    "admin@runnergateway.co.za",
    "0110000000",
    "ADMIN",
    adminPasswordHash,
  );

  // Insert Runner Profile (Gated Verification Flag)
  insertRunnerProfile.run(runner1Id, "Durban", "9501015000088", 1); // 1 = Verified by Admin

  // Insert Errand Request
  insertErrand.run(
    errand1Id,
    client1Id,
    runner1Id,
    "Durban",
    "Johannesburg",
    "PEP PAXI Point-to-Point",
    "Collect package from Durban Station and drop at PEP PAXI",
    350.0,
    "ACCEPTED",
  );

  // Insert Chat Messages (INTEGER Primary Keys auto-generated by SQLite: 1, 2, 3...)
  insertMessage.run(
    errand1Id,
    client1Id,
    "Hi Thabo, please confirm when you pick up the parcel.",
  );
  insertMessage.run(
    errand1Id,
    runner1Id,
    "Hi Sipho, I am currently at the collection point.",
  );
})();

console.log(
  "SQLite Database successfully initialized with primary keys and sample data.",
);

module.exports = db;
